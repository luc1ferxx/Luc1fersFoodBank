#!/usr/bin/env python3
"""Rebuilds backend/config/test-durations.properties from JUnit XML reports.

Usage:
    python3 backend/scripts/test-durations.py <dir with JUnit XML, searched recursively> \\
        [-o backend/config/test-durations.properties]

Every <testsuite> element names a test class (name) and its wall time in seconds (time). Nested classes
(Outer$Inner) are folded into their outer class, since the CI shards (-PtestShard in backend/build.gradle)
assign whole top-level classes. The file gets one line per top-level class, "fully.qualified.Name=<seconds>"
with one decimal, sorted by name, under a header that says how it is refreshed; the script prints the class
count and the total seconds. Refresh it occasionally (not per pull request) from a green CI run:

    gh run download <run id> -p 'backend-test-reports-*' -D <dir> && python3 backend/scripts/test-durations.py <dir>
"""
import argparse
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

HEADER = """\
# Measured wall time of each top-level backend test class, in seconds, from the JUnit XML of a green CI run
# (nested classes folded into their outer class). backend/build.gradle balances the CI test shards
# (-PtestShard=i/N) by these numbers; a class missing here is planned with the median of the others, so the
# file is refreshed occasionally, not per pull request, when the balance drifts or classes are renamed:
#
#   gh run download <run id> -p 'backend-test-reports-*' -D <dir> && python3 backend/scripts/test-durations.py <dir>
#
# Generated by backend/scripts/test-durations.py (do not edit by hand). TestDurationsFileTests fails when a
# class named here no longer exists.
"""
DEFAULT_OUTPUT = Path(__file__).resolve().parent.parent / "config" / "test-durations.properties"


def durations(reports_dir):
    """Seconds per top-level class, summed over every <testsuite> found under reports_dir."""
    seconds = defaultdict(float)
    for path in sorted(Path(reports_dir).rglob("*.xml")):
        try:
            root = ET.parse(path).getroot()
        except ET.ParseError as error:
            print(f"skipping {path}: {error}", file=sys.stderr)
            continue
        for suite in [root] if root.tag == "testsuite" else root.iter("testsuite"):
            name = suite.get("name", "")
            if name:
                seconds[name.split("$", 1)[0]] += float(suite.get("time") or 0)
    return {name: round(total, 1) for name, total in seconds.items()}


def main():
    parser = argparse.ArgumentParser(description="Writes the test durations file from JUnit XML reports.")
    parser.add_argument("reports", help="directory with JUnit XML reports, searched recursively")
    parser.add_argument("-o", "--output", type=Path, default=DEFAULT_OUTPUT,
                        help="properties file to write (default: %(default)s)")
    args = parser.parse_args()
    seconds = durations(args.reports)
    if not seconds:
        sys.exit(f"no <testsuite> elements found under {args.reports}")
    lines = [f"{name}={seconds[name]:.1f}" for name in sorted(seconds)]
    args.output.write_text(HEADER + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(seconds)} classes, {sum(seconds.values()):.1f} s in total -> {args.output}")


if __name__ == "__main__":
    main()
